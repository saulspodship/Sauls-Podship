/** Normalise a UI string for dictionary lookup. */
export const dictKey = (s: string): string =>
  s.replace(/\s+/g, ' ').replace(/\u2019/g, "'").trim();

/** Look a string up in the dictionary for a given language. */
export function translate(text: string, lang: LangCode): string | null {
  if (lang === 'en') return null;
  const hit = D[dictKey(text)];
  if (!hit) return null;
  const idx: Record<'ur' | 'hi' | 'ar', 0 | 1 | 2> = { ur: 0, hi: 1, ar: 2 };
  const out = hit[idx[lang]];
  return out || null;
}

