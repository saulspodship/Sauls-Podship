/**
 * build-i18n.mjs — compiles the site dictionary into runtime artifacts.
 *
 *   src/data/i18n/*.ts   ──▶  public/i18n/{ur,hi,ar}.json   (one file per language,
 *                                                       fetched only when that
 *                                                       language is selected)
 *   src/lib/i18n/standalone.ts ──▶ public/assets/sp-i18n.js  (IIFE for the static
 *                                                       module documents)
 *   content hash         ──▶  src/data/i18n/version.ts  (cache-buster for the JSON)
 *
 * Everything is generated at build time from files that are in Git; nothing
 * here calls a translation API and nothing in the runtime does either. English
 * visitors download none of it.
 *
 * Usage:
 *   node scripts/build-i18n.mjs           # write the artifacts
 *   node scripts/build-i18n.mjs --check   # fail if the committed artifacts are stale
 */
import { createHash } from 'crypto';
import fs from 'fs';
import os from 'os';
import path from 'path';
import { fileURLToPath, pathToFileURL } from 'url';
import { build as esbuild } from 'esbuild';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '..');
const publicDir = path.join(rootDir, 'public');
const i18nDir = path.join(publicDir, 'i18n');
const shimPath = path.join(publicDir, 'assets', 'sp-i18n.js');
const versionPath = path.join(rootDir, 'src', 'data', 'i18n', 'version.ts');
const CHECK = process.argv.includes('--check');

const LANGS = { ur: 0, hi: 1, ar: 2 };
const BANNER = '/* Saul\'s Podship site-wide language shim — generated by scripts/build-i18n.mjs. Do not edit. */';

/** Bundle a TS entry to a temp ESM file and import it (same trick prerender-seo.mjs uses). */
async function loadTsModule(entry, outfile) {
  await esbuild({
    entryPoints: [path.join(rootDir, entry)],
    outfile,
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node18',
    logLevel: 'silent',
  });
  return import(pathToFileURL(outfile).href);
}

async function main() {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'sp-i18n-'));
  const mod = await loadTsModule('src/data/i18n/index.ts', path.join(tmp, 'dict.mjs'));

  const MASTER = mod.MASTER;
  const PATTERNS = mod.MASTER_PATTERNS || [];
  if (!MASTER || typeof MASTER !== 'object') throw new Error('dictionary failed to load');

  /* ---- per-language dictionaries ---- */
  const payloads = {};
  for (const [lang, idx] of Object.entries(LANGS)) {
    const dict = {};
    for (const [key, tuple] of Object.entries(MASTER)) {
      const value = Array.isArray(tuple) ? tuple[idx] : null;
      if (typeof value === 'string' && value.trim()) dict[key] = value;
    }
    payloads[lang] = { v: 0, lang, dict, patterns: PATTERNS };
  }

  /* Version = hash of the payload contents, so browsers drop a stale copy the
     moment a translation changes (and not before). */
  const hash = createHash('sha1')
    .update(JSON.stringify(payloads))
    .digest('hex')
    .slice(0, 10);
  for (const lang of Object.keys(payloads)) payloads[lang].v = hash;

  const written = [];
  fs.mkdirSync(i18nDir, { recursive: true });
  for (const [lang, payload] of Object.entries(payloads)) {
    const file = path.join(i18nDir, `${lang}.json`);
    const body = JSON.stringify(payload);
    written.push({ file, body, lang, entries: Object.keys(payload.dict).length, bytes: Buffer.byteLength(body) });
  }

  /* ---- version.ts FIRST: the shim bundle inlines DICT_VERSION, so writing it
     afterwards would leave the committed shim one build behind (and make
     --check fail forever). ---- */
  const versionBody = `/**
 * @license
 * SPDX-License-Identifier: Apache-2.0
 */

/**
 * Dictionary cache-buster.
 *
 * GENERATED by scripts/build-i18n.mjs — do not edit by hand. It changes only
 * when a translation actually changes, so a returning visitor re-downloads
 * /i18n/<lang>.json exactly when there is something new in it.
 */
export const DICT_VERSION = '${hash}';
`;
  if (!CHECK) {
    const currentVersion = fs.existsSync(versionPath) ? fs.readFileSync(versionPath, 'utf8') : null;
    if (currentVersion !== versionBody) fs.writeFileSync(versionPath, versionBody);
  }
  written.push({ file: versionPath, body: versionBody, lang: 'version', entries: 0, bytes: Buffer.byteLength(versionBody) });

  /* ---- standalone shim for the static documents ---- */
  const shimEntry = path.join(tmp, 'shim-entry.ts');
  fs.copyFileSync(path.join(rootDir, 'src/lib/i18n/standalone.ts'), path.join(tmp, 'standalone.ts'));
  /* keep the relative imports of the copied entry resolvable */
  const shimSrc = fs.readFileSync(path.join(tmp, 'standalone.ts'), 'utf8')
    .replace(/from '\.\/(store|engine|fonts|types)'/g, (_, m) => `from '${path.join(rootDir, 'src/lib/i18n', m)}.ts'`);
  fs.writeFileSync(shimEntry, shimSrc);

  const shimBuild = await esbuild({
    entryPoints: [shimEntry],
    bundle: true,
    format: 'iife',
    target: ['es2018'],
    minify: true,
    legalComments: 'none',
    define: { '__SP_I18N_BUILD__': JSON.stringify(hash), 'process.env.NODE_ENV': '"production"' },
    write: false,
    logLevel: 'silent',
  });
  const shimBody = `${BANNER}\n${shimBuild.outputFiles[0].text}`;
  written.push({ file: shimPath, body: shimBody, lang: 'shim', entries: 0, bytes: Buffer.byteLength(shimBody) });

  let stale = 0;
  for (const item of written) {
    const current = fs.existsSync(item.file) ? fs.readFileSync(item.file, 'utf8') : null;
    if (current === item.body) continue;
    stale++;
    if (CHECK) continue;
    fs.mkdirSync(path.dirname(item.file), { recursive: true });
    fs.writeFileSync(item.file, item.body);
  }

  if (CHECK) {
    if (stale) {
      console.error(`[i18n] ${stale} generated artifact(s) are stale — run \`npm run gen:i18n\` and commit them.`);
      for (const item of written) {
        const current = fs.existsSync(item.file) ? fs.readFileSync(item.file, 'utf8') : null;
        if (current !== item.body) console.error(`  stale: ${path.relative(rootDir, item.file)}`);
      }
      process.exit(1);
    }
    console.log(`[i18n] artifacts up to date (v=${hash})`);
    return;
  }

  console.log(`[i18n] dictionary v=${hash}`);
  for (const item of written) {
    if (item.lang === 'shim' || item.lang === 'version') {
      console.log(`  ${path.relative(rootDir, item.file).padEnd(34)} ${(item.bytes / 1024).toFixed(1)} kB`);
    } else {
      console.log(`  ${path.relative(rootDir, item.file).padEnd(34)} ${String(item.entries).padStart(5)} entries  ${(item.bytes / 1024).toFixed(1)} kB`);
    }
  }
  console.log(`  patterns: ${PATTERNS.length}   master keys: ${Object.keys(MASTER).length}`);

  fs.rmSync(tmp, { recursive: true, force: true });
}

main().catch((err) => {
  console.error('[i18n] build failed:', err);
  process.exit(1);
});
